package de.soderer.fido2;

import static org.junit.jupiter.api.Assertions.assertDoesNotThrow;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeFalse;

import java.io.InputStream;
import java.util.Locale;

import org.junit.jupiter.api.Test;

@SuppressWarnings("static-method")
public class Fido2WindowsSupportTest {
	@Test
	public void testUsbSerialNumber() {
		assertEquals("205D329D304B", Fido2WindowsSupport.getUsbSerialNumber("USB\\VID_0483&PID_A2CA\\205D329D304B"));
	}

	@Test
	public void testUsbSerialNumberIsCaseInsensitiveOnPrefix() {
		assertEquals("abc123", Fido2WindowsSupport.getUsbSerialNumber("usb\\vid_1050&pid_0407\\abc123"));
	}

	@Test
	public void testUsbSerialNumberIsStripped() {
		assertEquals("SN1", Fido2WindowsSupport.getUsbSerialNumber("USB\\VID_1050&PID_0407\\ SN1 "));
	}

	@Test
	public void testUsbSerialNumberGeneratedByWindowsIsIgnored() {
		// Devices without serial number get an instance id part generated by Windows, which contains "&"
		assertNull(Fido2WindowsSupport.getUsbSerialNumber("USB\\VID_1050&PID_0407\\5&2A3B4C5D&0&1"));
	}

	@Test
	public void testUsbSerialNumberOfInvalidIds() {
		assertNull(Fido2WindowsSupport.getUsbSerialNumber(null));
		assertNull(Fido2WindowsSupport.getUsbSerialNumber(""));
		assertNull(Fido2WindowsSupport.getUsbSerialNumber("HID\\VID_1050&PID_0407&MI_01\\7&123&0&0000"));
		assertNull(Fido2WindowsSupport.getUsbSerialNumber("USB\\"));
		assertNull(Fido2WindowsSupport.getUsbSerialNumber("USB\\VID_1050&PID_0407\\"));
	}

	@Test
	public void testIsWindowsMatchesOsName() {
		final boolean expected = System.getProperty("os.name", "").toLowerCase(Locale.ROOT).startsWith("windows");
		assertEquals(expected, Fido2WindowsSupport.isWindows());
	}

	@Test
	public void testNeutralValuesOnOtherSystems() {
		assumeFalse(Fido2WindowsSupport.isWindows(), "Only on non-Windows systems");

		assertTrue(Fido2WindowsSupport.isRunningAsAdministrator());
		assertTrue(Fido2WindowsSupport.listSecurityKeyDescriptions().isEmpty());
		assertDoesNotThrow(Fido2WindowsSupport::extractBundledLibrariesIfNeeded);
	}

	@Test
	public void testIsRunningAsAdministratorIsStable() {
		// Cached after the first call (on Windows this starts "net session" once)
		assertEquals(Fido2WindowsSupport.isRunningAsAdministrator(), Fido2WindowsSupport.isRunningAsAdministrator());
	}

	@Test
	public void testBundledWindowsLibrariesArePackaged() throws Exception {
		for (final String libraryFileName : new String[] { "fido2.dll", "cbor.dll", "crypto-56.dll", "zlib1.dll" }) {
			try (InputStream resourceStream = Fido2WindowsSupport.class.getResourceAsStream("/win32-x86-64/" + libraryFileName)) {
				assertNotNull(resourceStream, "Missing bundled library resource: " + libraryFileName);
				assertTrue(resourceStream.readAllBytes().length > 0, "Empty bundled library resource: " + libraryFileName);
			}
		}
	}
}
